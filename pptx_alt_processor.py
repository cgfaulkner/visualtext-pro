class StagedBatchStatus:
    PENDING = "PENDING"
    STAGED = "STAGED"
    PROCESSED = "PROCESSED"
    VERIFIED = "VERIFIED"
    COMMITTED = "COMMITTED"
    FAILED = "FAILED"
    SKIPPED_EXISTING = "SKIPPED_EXISTING"


@dataclass
class StagedFileEntry:
    input_path: str
    relative_path: str
    staged_input_path: str
    staged_output_path: str
    final_output_path: str
    status: str = StagedBatchStatus.PENDING
    failure_reason: Optional[str] = None
    metrics: Dict[str, Any] = field(default_factory=dict)


class StagedBatchRunner:
    """
    Orchestrates staged batch processing for PPTX files.
    All processing happens against copies in a per-run staging directory.
    Final outputs are only written during the commit phase after verification.
    """

    def __init__(
        self,
        processor: PPTXAltProcessor,
        run_id: Optional[str] = None,
        staging_root: Optional[Path] = None,
        verify_min_coverage: Optional[float] = None,
        verify_min_processed_images: Optional[int] = None,
        alt_mismatch_mode: str = "warn",
        on_existing_output: str = "version",
        cleanup_backups: bool = False,
    ):
        self.processor = processor
        self.config = processor.config_manager.config

        # Autogenerated run_id: timestamp + short random token to avoid collisions
        self.run_id = run_id or f"{time.strftime('%Y%m%d_%H%M%S')}-{uuid.uuid4().hex[:8]}"
        self.staging_root = staging_root or (Path.cwd() / "staged_runs")
        self.run_dir = self.staging_root / self.run_id
        self.inputs_dir = self.run_dir / "inputs"
        self.outputs_dir = self.run_dir / "outputs"
        self.manifest_path = self.run_dir / "manifest.json"

        self.verify_min_coverage = verify_min_coverage
        self.verify_min_processed_images = verify_min_processed_images
        self.alt_mismatch_mode = alt_mismatch_mode
        self.on_existing_output = on_existing_output
        self.cleanup_backups = cleanup_backups

        self._manifest: Dict[str, Any] = {}
        self._files: Dict[str, StagedFileEntry] = {}

    # ---------------- Manifest helpers ----------------

    def _load_or_init_manifest(self, input_root: Path, final_output_root: Path) -> None:
        self.run_dir.mkdir(parents=True, exist_ok=True)
        self.inputs_dir.mkdir(parents=True, exist_ok=True)
        self.outputs_dir.mkdir(parents=True, exist_ok=True)

        if self.manifest_path.exists():
            try:
                with open(self.manifest_path, "r", encoding="utf-8") as f:
                    self._manifest = json.load(f)
            except Exception as exc:
                logger.warning(f"Failed to load staged manifest, starting fresh: {exc}")
                self._manifest = {}
        else:
            self._manifest = {}

        self._manifest.setdefault("run_id", self.run_id)
        self._manifest.setdefault("created_at", time.strftime("%Y-%m-%dT%H:%M:%S"))
        self._manifest.setdefault("input_root", str(input_root))
        self._manifest.setdefault("final_output_root", str(final_output_root))
        self._manifest.setdefault("staging_root", str(self.staging_root))
        self._manifest.setdefault("files", {})

        # Rebuild StagedFileEntry mapping from manifest
        files_section = self._manifest.get("files", {})
        for key, data in files_section.items():
            entry = StagedFileEntry(
                input_path=data["input_path"],
                relative_path=data["relative_path"],
                staged_input_path=data["staged_input_path"],
                staged_output_path=data["staged_output_path"],
                final_output_path=data["final_output_path"],
                status=data.get("status", StagedBatchStatus.PENDING),
                failure_reason=data.get("failure_reason"),
                metrics=data.get("metrics", {}),
            )
            self._files[key] = entry

    def _save_manifest(self) -> None:
        files_payload: Dict[str, Any] = {}
        for key, entry in self._files.items():
            files_payload[key] = {
                "input_path": entry.input_path,
                "relative_path": entry.relative_path,
                "staged_input_path": entry.staged_input_path,
                "staged_output_path": entry.staged_output_path,
                "final_output_path": entry.final_output_path,
                "status": entry.status,
                "failure_reason": entry.failure_reason,
                "metrics": entry.metrics,
            }
        self._manifest["files"] = files_payload
        with open(self.manifest_path, "w", encoding="utf-8") as f:
            json.dump(self._manifest, f, indent=2)

    # ---------------- Core workflow ----------------

    def run(
        self,
        input_dir: str,
        output_dir: Optional[str],
        pattern: str,
        export_pdf: bool,
    ) -> Dict[str, Any]:
        input_root = Path(input_dir)
        if not input_root.exists():
            raise FileNotFoundError(f"Input directory not found: {input_dir}")

        # Final output root: use explicit output_dir or config.paths.output_folder
        if output_dir:
            final_output_root = Path(output_dir)
        else:
            final_output_root = Path(
                self.config.get("paths", {}).get("output_folder", "reviewed_reports")
            )
        final_output_root.mkdir(parents=True, exist_ok=True)

        self._load_or_init_manifest(input_root, final_output_root)

        # Discover PPTX files (same as non-staged process_directory: glob only, no recursion)
        pptx_files = sorted(input_root.glob(pattern))
        if not pptx_files:
            logger.info(f"No PPTX files found for staged batch in: {input_root} (pattern={pattern})")
            return {
                "success": True,
                "total_files": 0,
                "processed_files": 0,
                "failed_files": 0,
                "skipped_files": 0,
                "total_processing_time": 0.0,
                "files": [],
            }

        results: Dict[str, Any] = {
            "success": True,
            "total_files": len(pptx_files),
            "processed_files": 0,
            "failed_files": 0,
            "skipped_files": 0,
            "total_processing_time": 0.0,
            "files": [],
        }

        start_time = time.time()

        for pptx_file in pptx_files:
            per_file_start = time.time()
            # Same output path contract as non-staged process_directory (flat)
            final_output_path = self.processor.get_batch_output_path(
                pptx_file, final_output_root
            )
            try:
                rel_path = pptx_file.relative_to(input_root)
            except ValueError:
                rel_path = Path(pptx_file.name)
            key = str(Path(pptx_file).resolve())
            # Staging layout: preserve relative dir to avoid collisions; filename = final name
            staged_input_path = self.inputs_dir / rel_path
            staged_output_dir = (self.outputs_dir / rel_path).parent
            staged_output_dir.mkdir(parents=True, exist_ok=True)
            staged_output_path = staged_output_dir / final_output_path.name

            final_output_path = Path(final_output_path)
            final_output_path.parent.mkdir(parents=True, exist_ok=True)

            entry = self._files.get(
                key,
                StagedFileEntry(
                    input_path=str(pptx_file),
                    relative_path=str(rel_path),
                    staged_input_path=str(staged_input_path),
                    staged_output_path=str(staged_output_path),
                    final_output_path=str(final_output_path),
                ),
            )

            staged_output = Path(entry.staged_output_path)

            # Resume semantics per status
            if entry.status == StagedBatchStatus.COMMITTED:
                # Terminal for this run_id
                logger.info(f"Skipping already committed file (staged run {self.run_id}): {pptx_file}")
                results["skipped_files"] += 1
                results["files"].append(
                    {
                        "success": True,
                        "input_file": entry.input_path,
                        "output_file": entry.final_output_path,
                        "status": entry.status,
                        "processing_time": 0.0,
                    }
                )
                self._files[key] = entry
                self._save_manifest()
                continue

            if entry.status == StagedBatchStatus.SKIPPED_EXISTING:
                # Treat as terminal by default for this run_id
                logger.info(f"Skipping file with status=SKIPPED_EXISTING: {pptx_file}")
                results["skipped_files"] += 1
                results["files"].append(
                    {
                        "success": True,
                        "input_file": entry.input_path,
                        "output_file": entry.final_output_path,
                        "status": entry.status,
                        "processing_time": 0.0,
                    }
                )
                self._files[key] = entry
                self._save_manifest()
                continue

            # VERIFIED with good staged output: commit directly without reprocessing
            if entry.status == StagedBatchStatus.VERIFIED and self._check_integrity(staged_output):
                commit_status = self._commit_file(entry, staged_output, Path(entry.final_output_path))
                entry.status = commit_status
                self._files[key] = entry
                self._save_manifest()

                per_file_time = time.time() - per_file_start

                if commit_status == StagedBatchStatus.COMMITTED:
                    results["processed_files"] += 1
                    results["files"].append(
                        {
                            "success": True,
                            "input_file": entry.input_path,
                            "output_file": entry.final_output_path,
                            "status": entry.status,
                            "processing_time": per_file_time,
                        }
                    )
                elif commit_status == StagedBatchStatus.SKIPPED_EXISTING:
                    results["skipped_files"] += 1
                    results["files"].append(
                        {
                            "success": True,
                            "input_file": entry.input_path,
                            "output_file": entry.final_output_path,
                            "status": entry.status,
                            "processing_time": per_file_time,
                        }
                    )
                else:
                    results["failed_files"] += 1
                    results["success"] = False
                    results["files"].append(
                        {
                            "success": False,
                            "input_file": entry.input_path,
                            "output_file": entry.final_output_path,
                            "status": entry.status,
                            "errors": [entry.failure_reason] if entry.failure_reason else [],
                            "processing_time": per_file_time,
                        }
                    )
                continue

            # For all other states (FAILED, PENDING, STAGED, PROCESSED, or VERIFIED with bad output),
            # reset to PENDING and re-run full processing from original input.
            if not staged_output.exists() or not self._check_integrity(staged_output):
                entry.status = StagedBatchStatus.PENDING
            else:
                # Even if a previous staged output exists, for non-VERIFIED states we prefer
                # to re-process from the original input for safety.
                entry.status = StagedBatchStatus.PENDING

            entry.failure_reason = None
            entry.metrics = entry.metrics or {}
            self._files[key] = entry
            self._save_manifest()

            try:
                # Stage input (fresh copy each time for safety)
                self._stage_input(Path(entry.input_path), Path(entry.staged_input_path))
                entry.status = StagedBatchStatus.STAGED
                self._files[key] = entry
                self._save_manifest()

                # Process staged copy
                process_result = self.processor.process_single_file(
                    entry.staged_input_path,
                    entry.staged_output_path,
                    export_pdf=export_pdf,
                    generate_coverage_report=True,
                )

                entry.metrics = {
                    "total_images": process_result.get("total_images"),
                    "processed_images": process_result.get("processed_images"),
                    "coverage_percent": process_result.get("coverage_percent"),
                    "failed_generations": len(process_result.get("failed_generations", [])),
                }

                if not process_result.get("success"):
                    entry.status = StagedBatchStatus.FAILED
                    entry.failure_reason = "; ".join(process_result.get("errors", [])) or "processing_failed"
                    results["failed_files"] += 1
                    results["success"] = False
                    self._files[key] = entry
                    self._save_manifest()
                    results["files"].append(
                        {
                            "success": False,
                            "input_file": entry.input_path,
                            "output_file": entry.final_output_path,
                            "status": entry.status,
                            "errors": process_result.get("errors", []),
                            "processing_time": time.time() - per_file_start,
                        }
                    )
                    continue

                entry.status = StagedBatchStatus.PROCESSED
                self._files[key] = entry
                self._save_manifest()

                # Verification
                if not self._verify_outputs(Path(entry.staged_output_path), entry):
                    entry.status = StagedBatchStatus.FAILED
                    results["failed_files"] += 1
                    results["success"] = False
                    self._files[key] = entry
                    self._save_manifest()
                    results["files"].append(
                        {
                            "success": False,
                            "input_file": entry.input_path,
                            "output_file": entry.final_output_path,
                            "status": entry.status,
                            "errors": [entry.failure_reason] if entry.failure_reason else [],
                            "processing_time": time.time() - per_file_start,
                        }
                    )
                    continue

                entry.status = StagedBatchStatus.VERIFIED
                self._files[key] = entry
                self._save_manifest()

                # Commit
                commit_status = self._commit_file(entry, Path(entry.staged_output_path), Path(entry.final_output_path))
                entry.status = commit_status
                self._files[key] = entry
                self._save_manifest()

                per_file_time = time.time() - per_file_start

                if commit_status == StagedBatchStatus.COMMITTED:
                    results["processed_files"] += 1
                    results["files"].append(
                        {
                            "success": True,
                            "input_file": entry.input_path,
                            "output_file": entry.final_output_path,
                            "status": entry.status,
                            "processing_time": per_file_time,
                        }
                    )
                elif commit_status == StagedBatchStatus.SKIPPED_EXISTING:
                    results["skipped_files"] += 1
                    results["files"].append(
                        {
                            "success": True,
                            "input_file": entry.input_path,
                            "output_file": entry.final_output_path,
                            "status": entry.status,
                            "processing_time": per_file_time,
                        }
                    )
                else:
                    # Treat anything else as failure
                    results["failed_files"] += 1
                    results["success"] = False
                    results["files"].append(
                        {
                            "success": False,
                            "input_file": entry.input_path,
                            "output_file": entry.final_output_path,
                            "status": entry.status,
                            "errors": [entry.failure_reason] if entry.failure_reason else [],
                            "processing_time": per_file_time,
                        }
                    )

            except Exception as exc:
                entry.status = StagedBatchStatus.FAILED
                entry.failure_reason = str(exc)
                self._files[key] = entry
                self._save_manifest()
                results["failed_files"] += 1
                results["success"] = False
                results["files"].append(
                    {
                        "success": False,
                        "input_file": entry.input_path,
                        "output_file": entry.final_output_path,
                        "status": entry.status,
                        "errors": [str(exc)],
                        "processing_time": time.time() - per_file_start,
                    }
                )

        results["total_processing_time"] = time.time() - start_time
        return results

    # ---------------- Individual steps ----------------

    def _stage_input(self, src: Path, dst: Path) -> None:
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dst)

    def _check_integrity(self, staged_output: Path) -> bool:
        """Return True if staged_output exists and can be opened as PPTX."""
        if not staged_output.exists():
            return False

        try:
            from pptx import Presentation  # type: ignore

            _ = Presentation(str(staged_output))
        except Exception:
            return False

        return True

    def _verify_outputs(self, staged_output: Path, entry: StagedFileEntry) -> bool:
        # Integrity: file must exist and be readable as PPTX
        if not self._check_integrity(staged_output):
            if not staged_output.exists():
                entry.failure_reason = "staged_output_missing"
            else:
                entry.failure_reason = "staged_output_not_readable"
            return False

        # Optional coverage checks
        coverage = entry.metrics.get("coverage_percent")
        if self.verify_min_coverage is not None and coverage is not None:
            if coverage < self.verify_min_coverage:
                entry.failure_reason = (
                    f"coverage_below_threshold: {coverage:.1f}% < {self.verify_min_coverage:.1f}%"
                )
                return False

        processed_images = entry.metrics.get("processed_images")
        if (
            self.verify_min_processed_images is not None
            and processed_images is not None
            and processed_images < self.verify_min_processed_images
        ):
            entry.failure_reason = (
                f"processed_images_below_threshold: {processed_images} < {self.verify_min_processed_images}"
            )
            return False

        # ALT readback mismatches: we currently treat failed_generations as proxy
        failed_generations = entry.metrics.get("failed_generations", 0) or 0
        if failed_generations and self.alt_mismatch_mode == "strict":
            entry.failure_reason = f"alt_readback_mismatch_count={failed_generations}"
            return False

        # In warn mode, we only record a note but do not fail verification
        if failed_generations and self.alt_mismatch_mode == "warn":
            entry.metrics["alt_readback_warning"] = failed_generations

        return True

    @staticmethod
    def _verify_artifact_dir(artifact_dir: Path) -> bool:
        """Verify artifact dir per plan: scan/visual_index.json and resolve/final_alt_map.json."""
        a = Path(artifact_dir)
        return (
            (a / "scan" / "visual_index.json").exists()
            and (a / "resolve" / "final_alt_map.json").exists()
        )

    def _commit_file(self, entry: StagedFileEntry, staged_output: Path, final_output: Path) -> str:
        final_output.parent.mkdir(parents=True, exist_ok=True)

        if self.on_existing_output not in {"skip", "version", "overwrite"}:
            self.on_existing_output = "version"

        # Paired artifacts: coverage report and PDF by staged stem and by input stem
        # (so we move input-stem report when staged output has a different name)
        staged_dir = staged_output.parent
        stem = staged_output.stem
        input_stem = Path(entry.input_path).stem
        paired_names = {
            f"{stem}_coverage_report.json",
            f"{stem}.pdf",
            f"{input_stem}_coverage_report.json",
            f"{input_stem}.pdf",
        }
        staged_artifacts: List[Path] = [
            p for p in staged_dir.iterdir()
            if p.is_file() and p != staged_output and p.name in paired_names
        ]

        # Establish base targets (without versioning) for PPTX and artifacts
        final_dir = final_output.parent
        pptx_base_target = final_output
        artifact_base_targets: List[Path] = [
            final_dir / a.name for a in staged_artifacts
        ]

        # Handle existing PPTX according to strategy
        if final_output.exists():
            if self.on_existing_output == "skip":
                # Do not move any staged outputs; mark as explicitly skipped
                entry.failure_reason = "existing_output_skipped"
                return StagedBatchStatus.SKIPPED_EXISTING

        # Determine version suffix (if any) for versioning strategy
        version_suffix: Optional[int] = None
        if final_output.exists() and self.on_existing_output == "version":
            version_suffix = self._next_version_number(final_output)

        # Compute final targets for PPTX and artifacts
        if version_suffix is not None:
            pptx_target = final_dir / f"{final_output.stem} ({version_suffix}){final_output.suffix}"
            artifact_targets: List[Path] = []
            for base in artifact_base_targets:
                artifact_targets.append(
                    base.parent / f"{base.stem} ({version_suffix}){base.suffix}"
                )
        else:
            pptx_target = pptx_base_target
            artifact_targets = artifact_base_targets

        # Overwrite strategy with backups for PPTX + all existing artifacts
        backups: List[Path] = []
        if self.on_existing_output == "overwrite":
            # Collect all final paths that currently exist (PPTX + artifacts)
            to_backup: List[Path] = []
            if pptx_base_target.exists():
                to_backup.append(pptx_base_target)
            for base in artifact_base_targets:
                if base.exists():
                    to_backup.append(base)

            # Create backups with collision-safe names
            for base in to_backup:
                backup = self._next_backup_path(base)
                try:
                    base.rename(backup)
                    backups.append(backup)
                except Exception as exc:
                    entry.failure_reason = f"failed_to_backup_existing_output: {exc}"
                    return StagedBatchStatus.FAILED

            # Now we will write into the non-versioned base targets
            pptx_target = pptx_base_target
            artifact_targets = artifact_base_targets

        # Pipeline artifact dir(s) in staged_dir (e.g. .alt_pipeline_*)
        pipeline_artifact_dirs: List[Path] = [
            p for p in staged_dir.iterdir()
            if p.is_dir() and p.name.startswith(".alt_pipeline_")
        ]

        try:
            final_dir_resolved = final_dir.resolve()
            staged_dev = staged_output.stat().st_dev
            final_dev = final_dir_resolved.stat().st_dev
            same_fs = staged_dev == final_dev
        except OSError:
            same_fs = False

        if same_fs:
            # Same-FS: (1) rename pipeline artifact dir(s), (2) rename PPTX, (3) rename paired files
            # Rollback pipeline dir(s) if PPTX rename fails
            moved_pipeline_dirs: List[tuple] = []  # (src, dst)
            for art_dir in pipeline_artifact_dirs:
                dst_name = art_dir.name
                if version_suffix is not None:
                    dst_name = f"{art_dir.name} ({version_suffix})"
                art_dst = final_dir / dst_name
                try:
                    art_dir.rename(art_dst)
                    moved_pipeline_dirs.append((art_dst, art_dir))
                    logger.info("Moving artifact dir %s to %s", art_dir, art_dst)
                except Exception as exc:
                    logger.debug("Rename artifact dir failed: %s", exc)
                    for _dst, _src in reversed(moved_pipeline_dirs):
                        try:
                            _dst.rename(_src)
                        except Exception as rollback_exc:
                            logger.warning("Rollback artifact dir failed: %s", rollback_exc)
                    entry.failure_reason = f"failed_to_move_artifact_dir: {exc}"
                    return StagedBatchStatus.FAILED
            try:
                staged_output.rename(pptx_target)
            except Exception as exc:
                for art_dst, art_src in reversed(moved_pipeline_dirs):
                    try:
                        art_dst.rename(art_src)
                        logger.debug("Rolled back artifact dir to %s", art_src)
                    except Exception as rollback_exc:
                        logger.warning("Rollback artifact dir failed: %s", rollback_exc)
                entry.failure_reason = f"commit_failed_after_artifact_move: {exc}"
                return StagedBatchStatus.FAILED
            for src, dst in zip(staged_artifacts, artifact_targets):
                dst.parent.mkdir(parents=True, exist_ok=True)
                src.rename(dst)
            if self.on_existing_output == "overwrite" and self.cleanup_backups:
                for backup in backups:
                    try:
                        if backup.exists():
                            backup.unlink()
                    except Exception:
                        pass
            entry.final_output_path = str(pptx_target)
            return StagedBatchStatus.COMMITTED

        # Cross-FS: copy + verify (plan rule: scan/visual_index.json, resolve/final_alt_map.json; .pptx)
        else:
            for art_dir in pipeline_artifact_dirs:
                art_dst = final_dir / art_dir.name
                if version_suffix is not None:
                    art_dst = final_dir / f"{art_dir.name} ({version_suffix})"
                try:
                    shutil.copytree(art_dir, art_dst, dirs_exist_ok=True)
                except Exception as exc:
                    logger.warning("Copy artifact dir failed: %s", exc)
                    entry.failure_reason = f"cross_fs_copy_artifact_dir_failed: {exc}"
                    return StagedBatchStatus.FAILED
                if not self._verify_artifact_dir(art_dst):
                    shutil.rmtree(art_dst, ignore_errors=True)
                    entry.failure_reason = "cross_fs_verify_artifact_dir_failed"
                    return StagedBatchStatus.FAILED
                logger.info("Copied and verified artifact dir %s to %s", art_dir, art_dst)
            try:
                shutil.copy2(staged_output, pptx_target)
            except Exception as exc:
                entry.failure_reason = f"cross_fs_copy_pptx_failed: {exc}"
                return StagedBatchStatus.FAILED
            if not (pptx_target.exists() and pptx_target.suffix.lower() == ".pptx"):
                pptx_target.unlink(missing_ok=True)
                entry.failure_reason = "cross_fs_verify_pptx_failed"
                return StagedBatchStatus.FAILED
            for src, dst in zip(staged_artifacts, artifact_targets):
                dst.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(src, dst)
            # Remove sources only after both verified
            try:
                for art_dir in pipeline_artifact_dirs:
                    shutil.rmtree(art_dir)
                staged_output.unlink()
                for src in staged_artifacts:
                    src.unlink(missing_ok=True)
            except Exception as exc:
                logger.warning("Cross-FS cleanup of sources failed (non-fatal): %s", exc)
            entry.final_output_path = str(pptx_target)
            return StagedBatchStatus.COMMITTED

    @staticmethod
    def _next_version_path(base: Path) -> Path:
        """
        Compute a non-destructive versioned filename next to base.
        Example: file.pptx -> file (2).pptx, file (3).pptx, etc.
        """
        parent = base.parent
        stem = base.stem
        suffix = base.suffix
        n = 2
        while True:
            candidate = parent / f"{stem} ({n}){suffix}"
            if not candidate.exists():
                return candidate
            n += 1

    @staticmethod
    def _next_version_number(base: Path) -> int:
        """
        Return the next available integer N such that base with suffix (N) does not exist.
        """
        parent = base.parent
        stem = base.stem
        suffix = base.suffix
        n = 2
        while True:
            candidate = parent / f"{stem} ({n}){suffix}"
            if not candidate.exists():
                return n
            n += 1

    def _next_backup_path(self, base: Path) -> Path:
        """
        Compute a collision-safe backup path for overwrite strategy:
        file.pptx -> file.__backup__<run_id>.pptx
        If that exists, use file.__backup__<run_id>-1.pptx, -2, etc.
        """
        parent = base.parent
        stem = base.stem
        suffix = base.suffix

        base_name = f"{stem}.__backup__{self.run_id}"
        candidate = parent / f"{base_name}{suffix}"
        if not candidate.exists():
            return candidate

        i = 1
        while True:
            candidate = parent / f"{base_name}-{i}{suffix}"
            if not candidate.exists():
                return candidate
            i += 1

    def _backup_to_original_path(self, backup: Path) -> Path:
        """
        Map a backup path back to the original filename. Handles both
        .__backup__<run_id> and .__backup__<run_id>-N suffixes.
        """
        # backup.stem is e.g. "file.__backup__run123" or "file.__backup__run123-1"
        if ".__backup__" not in backup.stem:
            return backup
        original_stem = backup.stem.split(".__backup__")[0]
        return backup.parent / (original_stem + backup.suffix)


